"""
metrics.py
==========
Performance metric calculations for the Sliding Window Protocol Simulator.

Definitions
-----------
- **Total transmission attempts**: Every time a packet is put on the channel
  (first send + all retransmissions).
- **Retransmissions**: transmission attempts beyond the first for each packet.
  retransmissions = total_attempts - total_unique_packets_sent_at_least_once.
- **Delivery rate**: (unique packets delivered / total intended packets) × 100.
- **Transmission efficiency**: (unique packets delivered / total transmission
  attempts) × 100.
- ACK transmissions are tracked separately and do NOT count toward data packet
  transmission metrics.
- Duplicate receptions at the receiver are not counted as additional unique
  deliveries.

All metric values are computed from the event log so they are always
consistent with the recorded simulation history.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

from network import EventType, SimEvent


@dataclass
class SimulationMetrics:
    """
    Computed performance metrics for one completed simulation run.

    Attributes
    ----------
    total_intended : int
        Total packets the sender was supposed to deliver.
    total_tx_attempts : int
        Total data-packet transmission attempts (first sends + retransmissions).
    total_retransmissions : int
        Retransmission attempts only (= total_tx_attempts - first-send count).
    unique_delivered : int
        Unique packets successfully delivered to the application layer.
    delivery_rate : float
        unique_delivered / total_intended × 100  [percent].
    transmission_efficiency : float
        unique_delivered / total_tx_attempts × 100  [percent].
        0.0 if total_tx_attempts == 0.
    total_ack_sent : int
        Number of ACK frames generated by the receiver.
    total_ack_lost : int
        Number of ACK frames lost in the channel.
    total_pkt_lost : int
        Number of data packets lost in the channel.
    simulation_time : float
        Simulated timestamp of the last recorded event.
    completed : bool
        True if the simulation finished without hitting the retry limit.
    protocol : str
        "GBN" or "SR".
    """
    total_intended:         int   = 0
    total_tx_attempts:      int   = 0
    total_retransmissions:  int   = 0
    unique_delivered:       int   = 0
    delivery_rate:          float = 0.0
    transmission_efficiency:float = 0.0
    total_ack_sent:         int   = 0
    total_ack_lost:         int   = 0
    total_pkt_lost:         int   = 0
    total_pkt_corrupted:    int   = 0
    simulation_time:        float = 0.0
    completed:              bool  = False
    protocol:               str   = ""

    def as_dict(self) -> dict:
        """Return metrics as a plain dictionary (for the frontend)."""
        return {
            "protocol":               self.protocol,
            "total_intended":         self.total_intended,
            "total_tx_attempts":      self.total_tx_attempts,
            "total_retransmissions":  self.total_retransmissions,
            "unique_delivered":       self.unique_delivered,
            "delivery_rate":          round(self.delivery_rate, 2),
            "transmission_efficiency":round(self.transmission_efficiency, 2),
            "total_ack_sent":         self.total_ack_sent,
            "total_ack_lost":         self.total_ack_lost,
            "total_pkt_lost":         self.total_pkt_lost,
            "total_pkt_corrupted":    self.total_pkt_corrupted,
            "simulation_time":        self.simulation_time,
            "completed":              self.completed,
        }


def calculate_metrics(
    events: list[SimEvent],
    total_intended: int,
    protocol: str,
) -> SimulationMetrics:
    """
    Derive all performance metrics from the event log.

    Parameters
    ----------
    events : list[SimEvent]
        Ordered list of SimEvent objects recorded during the simulation.
    total_intended : int
        Total unique packets the sender was supposed to deliver.
    protocol : str
        "GBN" or "SR".

    Returns
    -------
    SimulationMetrics
        Populated metrics dataclass.

    Notes
    -----
    - PACKET_SENT and RETRANSMISSION both represent a transmission attempt on
      the channel. PACKET_SENT is the *first* send; RETRANSMISSION is every
      subsequent attempt.
    - PACKET_DELIVERED events count unique deliveries (duplicates appear as
      PACKET_DUPLICATE and are excluded).
    - ACK_SENT / ACK_LOST are receiver-side ACK statistics.
    - SIMULATION_DONE indicates clean completion; SIMULATION_FAILED indicates
      the retry limit was hit.
    """
    m = SimulationMetrics(protocol=protocol, total_intended=total_intended)

    first_sends:        set[Optional[int]] = set()
    retransmit_indices: set[Optional[int]] = set()
    delivered_indices:  set[Optional[int]] = set()

    for evt in events:
        et = evt.event_type

        if et == EventType.PACKET_SENT:
            m.total_tx_attempts += 1
            first_sends.add(evt.seq_num)

        elif et == EventType.RETRANSMISSION:
            m.total_tx_attempts += 1
            retransmit_indices.add(evt.seq_num)

        elif et == EventType.PACKET_LOST:
            m.total_pkt_lost += 1

        elif et == EventType.PACKET_CORRUPTED:
            m.total_pkt_corrupted += 1

        elif et == EventType.PACKET_DELIVERED:
            # Guard against double-counting if engine emits duplicate DELIVERED events
            if evt.seq_num not in delivered_indices:
                delivered_indices.add(evt.seq_num)
                m.unique_delivered += 1

        elif et == EventType.ACK_SENT:
            m.total_ack_sent += 1

        elif et == EventType.ACK_LOST:
            m.total_ack_lost += 1

        elif et == EventType.SIMULATION_DONE:
            m.completed = True

    # Retransmissions = attempts beyond the first per unique packet
    m.total_retransmissions = len(retransmit_indices)

    # Simulation time = timestamp of the last event
    if events:
        m.simulation_time = events[-1].time

    # Derived rates
    if total_intended > 0:
        m.delivery_rate = (m.unique_delivered / total_intended) * 100.0
    if m.total_tx_attempts > 0:
        m.transmission_efficiency = (m.unique_delivered / m.total_tx_attempts) * 100.0

    return m
